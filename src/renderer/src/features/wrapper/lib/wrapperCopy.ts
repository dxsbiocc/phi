export const wrapperCopy = defineCopy(english, chinese)

// Preserve raw diagnostics while refreshing fixed messages saved in async UI state.
const fixedMessageKeys = new Map<string, keyof typeof english>()
for (const key of Object.keys(english) as (keyof typeof english)[]) {
  const en = english[key]
  const zh = chinese[key]
  if (typeof en === 'string' && typeof zh === 'string') {
    fixedMessageKeys.set(en, key)
    fixedMessageKeys.set(zh, key)
  }
}

export function localizeWrapperMessage(message: string): string {
  const key = fixedMessageKeys.get(message)
  if (!key) return message
  const localized = wrapperCopy[key]
  return typeof localized === 'string' ? localized : message
}
